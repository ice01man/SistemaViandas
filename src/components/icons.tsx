import type { ReactNode, SVGProps } from "react";

/**
 * Íconos outline (trazo estilo Lucide, 24x24, stroke currentColor).
 * Tamaño por className (default h-4 w-4); heredan el color del texto.
 */
function createIcon(children: ReactNode) {
  return function Icon({ className = "h-4 w-4", ...rest }: SVGProps<SVGSVGElement>) {
    return (
      <svg
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        className={className}
        {...rest}
      >
        {children}
      </svg>
    );
  };
}

